/*
 * VGA mode-set register tables, taken from frank-286's BIOS INT 10h.
 *
 * Setting an EGA or VGA mode means writing a misc output register, five
 * sequencer registers, twenty-five CRTC registers, nine graphics
 * controller registers and twenty-one attribute registers, in that order
 * and with the right values for each mode. GLaBIOS is an XT BIOS and
 * knows none of it, and these numbers are not the sort of thing to derive:
 * they are a table, and frank-286 already has a correct one.
 *
 * The option ROM names a BIOS mode number through port 0x3DC and this
 * plays the corresponding table into the emulated card, which is the
 * same sequence real hardware would have received from a real video BIOS.
 */
