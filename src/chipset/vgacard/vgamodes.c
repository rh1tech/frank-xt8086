const VgaMode *vgamodes_find(const uint8_t mode) {
    for (unsigned i = 0; i < sizeof vga_modes / sizeof vga_modes[0]; i++)
        if (vga_modes[i].mode == mode) return &vga_modes[i];
    return NULL;
}
